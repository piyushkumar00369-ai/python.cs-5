a = int(input("\nEnter first value for a: "))
b = int(input("\nEnter second value for b: "))
print("AND:", (a > 5 and b > 15))

# Example for or operator
c = int(input("\nEnter value for c: "))
d = int(input("\nEnter value for d: "))
print("OR:", (c > 5 or d > 5))

# Example for not operator
e = int(input("\nEnter value for e: "))
print("NOT:", not (e > 10))
