a = int(input("Enter first integer: "))
b = int(input("Enter second integer: "))

# Bitwise AND
print("a & b =", a & b)

# Bitwise OR
print("a | b =", a | b)

# Bitwise XOR
print("a ^ b =", a ^ b)

# Bitwise NOT
print("~a =", ~a)
print("~b =", ~b)

# Left shift
print("a << 1 =", a << 1)
print("b << 1 =", b << 1)

# Right shift
print("a >> 1 =", a >> 1)
print("b >> 1 =", b >> 1)