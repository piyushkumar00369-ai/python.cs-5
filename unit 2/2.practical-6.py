a = int(input("Enter first integer: "))
b = int(input("Enter second integer: "))

# Bitwise AND
print("\na & b =", a & b)

# Bitwise OR
print("\na | b =", a | b)

# Bitwise XOR
print("\na ^ b =", a ^ b)

# Bitwise NOT
print("\n~a =", ~a)
print("~b =", ~b)

# Left shift
print("\na << 1 =", a << 1)
print("b << 1 =", b << 1)

# Right shift
print("\na >> 1 =", a >> 1)
print("b >> 1 =", b >> 1)