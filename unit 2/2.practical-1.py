a = float(input("Enter first number: "))
b = float(input("Enter second number: "))

# Addition
add = a + b

# Subtraction
sub = a - b

# Multiplication
mul = a * b

# Division
div = a / b

# Modulus
mod = a % b

# Floor Division
floor_div = a // b

# Exponentiation
exp = a ** b

# Display the results
print("Addition:", add)
print("Subtraction:", sub)
print("Multiplication:", mul)
print("Division:", div)
print("Modulus:", mod)
print("Floor Division:", floor_div)
print("Exponentiation:", exp)